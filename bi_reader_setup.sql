-- Read-only Snowflake role and login for the BI tool (MicroStrategy / Strategy Mosaic).
-- The BI layer can only SELECT from the dbt marts; it cannot see RAW_SAP or STAGING.
--
-- Trial accounts allow single-factor password logins. On a production account, use
-- key-pair authentication (TYPE = SERVICE) instead of a password.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS BI_READER;
GRANT USAGE ON WAREHOUSE CSTORE_WH TO ROLE BI_READER;
GRANT USAGE ON DATABASE CSTORE TO ROLE BI_READER;
GRANT USAGE ON SCHEMA CSTORE.MARTS TO ROLE BI_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA CSTORE.MARTS TO ROLE BI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CSTORE.MARTS TO ROLE BI_READER;

CREATE USER IF NOT EXISTS MSTR_READER
  PASSWORD = '<set-your-own>'
  DEFAULT_ROLE = BI_READER
  DEFAULT_WAREHOUSE = CSTORE_WH
  DEFAULT_NAMESPACE = CSTORE.MARTS
  MUST_CHANGE_PASSWORD = FALSE;
GRANT ROLE BI_READER TO USER MSTR_READER;

SHOW GRANTS TO ROLE BI_READER;
